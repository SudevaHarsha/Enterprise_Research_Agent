#!/usr/bin/env python3
"""Generate ``docs/licenses.md`` — the model & library inventory (task_015).

Pure-stdlib implementation (Python 3.12+): reads the *installed* distributions
via :mod:`importlib.metadata`, classifies each against the dependencies declared
in ``pyproject.toml`` (read via :mod:`tomllib`), and renders the full ECRKE
license inventory document. No new dependencies are introduced; the document is
regenerated reproducibly:

    python scripts/generate_licenses.py

The table format mirrors ``pip-licenses`` (Name | Version | License) with a
``Role`` column added to distinguish runtime / dev / transitive packages. If a
distribution exposes no license metadata, the cell reads ``UNKNOWN`` — the
reader must verify it from the package's own metadata before any legal review.
"""

from __future__ import annotations

import importlib.metadata
import re
import sys
import tomllib
from collections.abc import Iterable
from datetime import UTC, datetime
from pathlib import Path

# Leading name token of a PEP 508 dependency specifier (stops at extras/version).
_NAME_TOKEN = re.compile(r"^[A-Za-z0-9._-]+")
# Long license strings (full license text in metadata) are truncated in the table.
_MAX_LICENSE_LEN = 80

ROOT = Path(__file__).resolve().parents[1]
PYPROJECT = ROOT / "pyproject.toml"
OUTPUT = ROOT / "docs" / "licenses.md"

# Static prose sections (not derivable from installed metadata). These are the
# same statements a human reviewer would write; keeping them in the generator
# means the document regenerates as one unit.
DOC_HEADER = """# ECRKE — Model & Library Inventory with Licenses

| Field | Value |
|---|---|
| **Document** | Submission-pack artifact 5 (build-plan §2): model & library inventory with licenses |
| **Generated by** | `scripts/generate_licenses.py` (stdlib `importlib.metadata` — no new dependencies) |
| **Scope** | Python runtime deps, dev deps, full installed inventory, LLM provider terms, UI/fonts, sample data |
| **Reproduce** | `.venv\\Scripts\\python.exe scripts\\generate_licenses.py` (exit 0) |

---

## 1. Method

The inventory below is generated from the **actual installed distributions** in
this environment (`importlib.metadata.distributions()`), classified against the
dependencies declared in `pyproject.toml`:

| Role | Meaning |
|---|---|
| **runtime** | Declared in `[project].dependencies` — required to run the application |
| **dev** | Declared in `[project.optional-dependencies].dev` — required to develop/test |
| **transitive** | Installed as a dependency of a runtime/dev package (not declared directly) |
| **project** | The ECRKE package itself (`ecrke`, editable install) |

License metadata is read from each distribution's metadata in this order:
`License-Expression` (PEP 639), the `License` field, then `License :: OSI Approved ::
...` classifiers; otherwise the cell reads `UNKNOWN` and must be verified from
the package's own metadata. Long license texts are truncated to 80 characters in
the table (full text lives in each package's metadata). The table format mirrors
`pip-licenses` (Name | Version | License) with a `Role` column appended.
"""

