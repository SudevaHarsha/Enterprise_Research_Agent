def normalize(name: str) -> str:
    """Normalize a package name for comparison (PEP 503: casefold, strip -_ )."""
    return name.replace("_", "").replace("-", "").casefold()


def declared_names(entries: Iterable[str]) -> set[str]:
    """Extract base distribution names from dependency specifiers."""
    names: set[str] = set()
    for entry in entries:
        match = _NAME_TOKEN.match(entry.strip())
        if match:
            names.add(normalize(match.group(0)))
    return names


def dist_license(dist: importlib.metadata.Distribution) -> str:
    """Best-effort license string from a distribution's metadata."""
    meta = dist.metadata
    expression = meta.get("License-Expression")
    if expression:
        return _truncate(expression)
    license_field = (meta.get("License") or "").strip()
    if license_field and license_field.upper() != "UNKNOWN":
        return _truncate(license_field)
    classifiers = meta.get_all("Classifier") or []
    for classifier in classifiers:
        if classifier.startswith("License :: OSI Approved ::"):
            return _truncate(classifier.rsplit("::", 1)[-1].strip())
    for classifier in classifiers:
        if classifier.startswith("License ::"):
            return _truncate(classifier.rsplit("::", 1)[-1].strip())
    return "UNKNOWN"


def _truncate(value: str) -> str:
    """Truncate long license texts for a readable table cell."""
    compact = " ".join(value.split())
    if len(compact) <= _MAX_LICENSE_LEN:
        return compact
    return compact[:_MAX_LICENSE_LEN].rstrip() + " … (truncated)"


def render_table(rows: list[tuple[str, str, str, str]]) -> str:
    """Render a Name | Version | License | Role markdown table."""
    lines = ["| Name | Version | License | Role |", "|---|---|---|---|"]
    for name, version, license_, role in rows:
        safe = license_.replace("|", "\\|").replace("\n", " ")
        lines.append(f"| {name} | {version} | {safe} | {role} |")
    return "\n".join(lines)


def main() -> int:
    """Generate ``docs/licenses.md`` from installed metadata; exit 0 on success."""
    with PYPROJECT.open("rb") as handle:
        project = tomllib.load(handle)
    runtime_declared = declared_names(project["project"]["dependencies"])
    dev_declared = declared_names(project["project"]["optional-dependencies"]["dev"])

    dists = sorted(
        importlib.metadata.distributions(), key=lambda d: (d.metadata["Name"] or "").casefold()
    )

    runtime_rows: list[tuple[str, str, str, str]] = []
    dev_rows: list[tuple[str, str, str, str]] = []
    transitive_rows: list[tuple[str, str, str, str]] = []
    for dist in dists:
        name = dist.metadata["Name"] or "?"
        version = dist.version or "?"
        license_ = dist_license(dist)
        key = normalize(name)
        if key == normalize("ecrke"):
            continue  # the project itself, noted in the header
        if key in runtime_declared:
            role = "runtime"
            runtime_rows.append((name, version, license_, role))
        elif key in dev_declared:
            role = "dev"
            dev_rows.append((name, version, license_, role))
        else:
            role = "transitive"
            transitive_rows.append((name, version, license_, role))

    missing = sorted(
        normalize(name)
        for name in (runtime_declared | dev_declared)
        if name not in {normalize(d.metadata["Name"] or "") for d in dists}
    )

    ts = datetime.now(UTC).strftime("%Y-%m-%dT%H:%M:%SZ")
    parts = [
        DOC_HEADER,
        "## 2. Python Runtime Dependencies (installed)\n",
        render_table(runtime_rows),
        "\n## 3. Python Dev Dependencies (installed)\n",
        render_table(dev_rows),
        "\n## 4. Full Installed Inventory (incl. transitive)\n",
        render_table(transitive_rows),
        "",
        DOC_PROVIDER_TERMS,
        DOC_UI_FONTS,
        DOC_SAMPLE_DATA.format(ts=ts, python=sys.version.split()[0]),
    ]
    if missing:
        parts.append(
            "\n> **Declared but not installed in this environment:** "
            + ", ".join(sorted(missing))
            + "\n"
        )
    OUTPUT.write_text("\n".join(parts), encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
